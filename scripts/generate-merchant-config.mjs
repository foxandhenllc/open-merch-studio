import prettier from "prettier";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { renderMerchantConfigModule } from "./merchant-config.mjs";
import { renderPolicyModule } from "./policy-content.mjs";
import { loadInstallationProfile } from "./installation-profile.mjs";

const outputs = [
  resolve("backend/src/generated/merchant-config.ts"),
  resolve("frontend/src/generated/merchant-config.ts"),
];
const { config, policy } = loadInstallationProfile();
const rendered = await renderMerchantConfigModule(config);
const checkOnly = process.argv.includes("--check");

const artifacts = outputs.map((output) => [output, rendered]);
artifacts.push([
  resolve("frontend/src/generated/policy-content.ts"),
  await renderPolicyModule(policy),
]);
artifacts.push([
  resolve("backend/src/generated/policy-approval.ts"),
  await renderPolicyModule(policy, true),
]);
artifacts.push([
  resolve("backend/src/generated/store-profile.ts"),
  await prettier.format(
    `// Generated by config:generate. Private draft editing starts from this published profile.\nimport type { PolicyDocument } from '@open-merch-studio/merchant-profile';\nexport const installedPolicy: PolicyDocument = ${JSON.stringify(policy, null, 2)};\n`,
    {
      parser: "typescript",
      singleQuote: true,
      printWidth: 100,
      trailingComma: "es5",
    },
  ),
]);
for (const [output, rendered] of artifacts) {
  if (checkOnly) {
    if (!existsSync(output))
      throw new Error(`${output} is missing. Run npm run config:generate.`);
    if (readFileSync(output, "utf8") !== rendered)
      throw new Error(`${output} is stale. Run npm run config:generate.`);
  } else {
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, rendered);
  }
}
console.log(
  `${checkOnly ? "Verified" : "Generated"} typed merchant configuration.`,
);
